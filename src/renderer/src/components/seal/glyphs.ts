/** The carved glyph for a word's first letter; Vietnamese initials (Ư, Ơ, Â, Đ, …) carve as their base letter. */
export function sealGlyph(term: string): readonly string[] | null {
  const first = term.trim().charAt(0)
  if (!first) return null
  const base = first.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[đĐ]/, 'D').toUpperCase()
  return GLYPHS[base] ?? null
}
